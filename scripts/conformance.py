#!/usr/bin/env python3
"""Writes docs/CONFORMANCE.md from docs/conformance.toml.

    python3 scripts/conformance.py          # rewrite the document
    python3 scripts/conformance.py --check  # fail if it is out of date

Standard library only (tomllib, Python 3.11+).
"""
import pathlib
import sys

if sys.version_info < (3, 11):
    sys.exit("conformance.py needs Python 3.11 or newer (for tomllib)")
import tomllib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "docs" / "conformance.toml"
TARGET = ROOT / "docs" / "CONFORMANCE.md"

LAYERS = [
    ("shred-ingest", "Shred ingest", "The fetch filter, sanitize, signature check and erasure recovery."),
    ("blockstore", "Blockstore", "Insert, parent information, fullness and the block id."),
    ("component", "Components", "Cutting a slot's shreds into components and parsing them."),
    ("state-machine", "Block state machine", "The order of header, entries, footer and final tick."),
    ("entries", "Entries", "Ticks and the hash chain."),
    ("transactions", "Transactions", "What kills a block and what merely fails."),
    ("finality", "Finalization", "Certificates."),
    ("malleable", "Bytes that may differ", "What two honest validators can hold differently for the same block id."),
]
STATUS = {
    "enforced": "Enforced",
    "implied": "Implied",
    "documented": "Documented",
    "planned": "Planned",
    "na": "n/a",
}


def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def render() -> str:
    doc = tomllib.loads(SOURCE.read_text())
    checks = doc["check"]
    counts = {k: sum(1 for c in checks if c["status"] == k) for k in STATUS}
    out = [
        "# Conformance ledger",
        "",
        "<!-- Generated by scripts/conformance.py from docs/conformance.toml. Edit that file. -->",
        "",
        f"Every check an Agave {doc['agave_tag']} validator applies between a data shred",
        "arriving and a transaction counting as executed in a finalized block, and",
        "what the verifier does about each. The verifier does far less work than a",
        "validator; this is the argument that it does enough.",
        "",
        f"{len(checks)} checks: {counts['enforced']} enforced, {counts['implied']} implied,",
        f"{counts['documented']} documented, {counts['planned']} planned, {counts['na']} not about block content.",
        "",
        "- **Enforced**: the verifier applies the same rule or a stricter one. The",
        "  named test shows it.",
        "- **Implied**: the verifier does not check it. A block that fails it is",
        "  never finalized, for the reason the named premise gives.",
        "- **Documented**: nothing a proof can settle. The documentation says what",
        "  a successful check does and does not mean.",
        "- **Planned**: should be enforced and is not yet.",
        "",
        "## Premises",
        "",
        "An implied row is only as good as the premise it cites. Each premise is",
        "meant to be shown by cases in the differential oracle",
        "(`tools/agave-fixtures`), which runs Agave's own code.",
        "",
    ]
    for p in doc["premise"]:
        used = sum(1 for c in checks if c.get("premise") == p["id"])
        out.append(f"- **`{p['id']}`** ({used} rows). {p['text']}")
        if p.get("note"):
            out.append(f"  {p['note']}")
        cases = p.get("oracle_cases") or []
        out.append("  Oracle cases: " + (", ".join(f"`{c}`" for c in cases) if cases else "none yet."))
    out.append("")
    for key, title, blurb in LAYERS:
        rows = [c for c in checks if c["layer"] == key]
        out += [f"## {title}", "", blurb, "", "| # | Check | Agave | If it fails | Verifier |", "|---|---|---|---|---|"]
        for c in rows:
            if c["status"] in ("enforced", "planned"):
                how = f"{STATUS[c['status']]}: `{c['test']}`"
            elif c["status"] == "implied":
                how = f"Implied: `{c['premise']}`"
            else:
                how = STATUS[c["status"]]
            if c.get("note"):
                how += f". {c['note']}"
            where = c["agave"]
            if c.get("error"):
                where += f" ({c['error']})" if where else c["error"]
            out.append(f"| {c['id']} | {cell(c['check'])} | {cell(where)} | {cell(c['consequence'])} | {cell(how)} |")
        out.append("")
    return "\n".join(out)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not TARGET.exists() or TARGET.read_text() != text:
            print("docs/CONFORMANCE.md is out of date; run scripts/conformance.py", file=sys.stderr)
            return 1
        return 0
    TARGET.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
